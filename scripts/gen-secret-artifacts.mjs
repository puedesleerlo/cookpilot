/**
 * Generates `.env.example` and `infra/iam.sh` from the secret inventory.
 *
 * Generated rather than hand-maintained so the three cannot disagree: a secret added to
 * the inventory without an IAM binding is a service that starts and then cannot read it,
 * and a binding without an inventory entry is access nobody audits.
 *
 * Run: node scripts/gen-secret-artifacts.mjs
 */
import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * The inventory is TypeScript, and this script is plain Node. Rather than add a compile
 * step, parse the declarations out of the source -- and fail loudly if the shape changes,
 * so this never silently generates an empty file.
 */
const source = readFileSync(path.join(root, 'apps/api/src/config/secrets.ts'), 'utf8');
const block = source.slice(source.indexOf('export const SECRETS = ['), source.indexOf('] as const satisfies'));

const secrets = [...block.matchAll(/\{\s*name:\s*'([^']+)',\s*required:\s*(true|false),\s*services:\s*\[([^\]]*)\],\s*description:\s*'([^']*)',\s*source:\s*'([^']*)',\s*\}/g)].map(
  (m) => ({
    name: m[1],
    required: m[2] === 'true',
    services: [...m[3].matchAll(/'([^']+)'/g)].map((s) => s[1]),
    description: m[4],
    source: m[5],
  }),
);

if (secrets.length === 0) {
  console.error('gen-secret-artifacts: parsed zero secrets. The inventory shape changed; fix this script.');
  process.exit(1);
}

// ------------------------------------------------------------- .env.example

const envLines = [
  '# Kitchen Compiler - local environment.',
  '#',
  '# Copy to .env and fill in. .env is gitignored and must never be committed.',
  '# In Cloud Run these come from Secret Manager, mounted by PINNED VERSION, never "latest".',
  '#',
  '# Generated by scripts/gen-secret-artifacts.mjs from apps/api/src/config/secrets.ts.',
  '# Edit the inventory, not this file.',
  '',
  '# --- The model provider needs no secret. ---',
  '# Vertex AI authenticates through the Cloud Run service account (Application Default',
  '# Credentials). Locally, run: gcloud auth application-default login',
  'GOOGLE_CLOUD_PROJECT=',
  'VERTEX_LOCATION=global',
  '',
];

for (const group of [true, false]) {
  const inGroup = secrets.filter((s) => s.required === group);
  if (inGroup.length === 0) continue;
  envLines.push(`# --- ${group ? 'Required' : 'Optional'} ---`);
  for (const s of inGroup) {
    envLines.push(`# ${s.description}`);
    envLines.push(`# Source: ${s.source}`);
    envLines.push(`# Read by: ${s.services.join(', ')}`);
    envLines.push(`${s.name}=`);
    envLines.push('');
  }
}

envLines.push('# --- Public client config. Safe to ship in the bundle. ---');
envLines.push('VITE_API_URL=http://localhost:8080');
envLines.push('VITE_SENTRY_DSN_CLIENT=');
envLines.push('');

writeFileSync(path.join(root, '.env.example'), envLines.join('\n'));

// ----------------------------------------------------------------- iam.sh

const services = [...new Set(secrets.flatMap((s) => s.services))].sort();

const iam = [
  '#!/usr/bin/env bash',
  '#',
  '# Grants each Cloud Run service account read access to exactly the secrets its service',
  '# declares -- and nothing else. The worker has no reason to read the voice key, and this',
  '# is where that stops being a matter of trust.',
  '#',
  '# Generated by scripts/gen-secret-artifacts.mjs. Edit the inventory, not this file.',
  '#',
  '# Usage: PROJECT_ID=your-project ./infra/iam.sh',
  '',
  'set -euo pipefail',
  '',
  ': "${PROJECT_ID:?set PROJECT_ID}"',
  '',
  ...services.map((s) => `SA_${s.toUpperCase()}="kc-${s}@\${PROJECT_ID}.iam.gserviceaccount.com"`),
  '',
  '# --- Service accounts ---',
  ...services.flatMap((s) => [
    `gcloud iam service-accounts create kc-${s} --project="$PROJECT_ID" \\`,
    `  --display-name="Kitchen Compiler ${s}" || true`,
  ]),
  '',
  '# --- Secrets ---',
  ...secrets.flatMap((s) => [
    `# ${s.name}: ${s.description}`,
    `gcloud secrets create ${s.name} --project="$PROJECT_ID" --replication-policy=automatic || true`,
    ...s.services.map(
      (svc) =>
        `gcloud secrets add-iam-policy-binding ${s.name} --project="$PROJECT_ID" \\\n` +
        `  --member="serviceAccount:\${SA_${svc.toUpperCase()}}" --role="roles/secretmanager.secretAccessor"`,
    ),
    '',
  ]),
  '# --- Vertex AI: no secret, just the role. ---',
  ...services.map(
    (s) =>
      `gcloud projects add-iam-policy-binding "$PROJECT_ID" \\\n` +
      `  --member="serviceAccount:\${SA_${s.toUpperCase()}}" --role="roles/aiplatform.user"`,
  ),
  '',
  'echo "IAM configured. Mount every secret by an explicit version number, never the"',
  'echo "floating alias -- rotation should be a deploy you can see and roll back:"',
  'echo "  gcloud run deploy api --update-secrets=BRAVE_API_KEY=BRAVE_API_KEY:7"',
  '',
].join('\n');

mkdirSync(path.join(root, 'infra'), { recursive: true });
writeFileSync(path.join(root, 'infra/iam.sh'), iam, { mode: 0o755 });

console.log(
  `generated .env.example (${secrets.length} secrets) and infra/iam.sh (${services.length} services)`,
);
for (const s of secrets) {
  console.log(`  ${s.required ? 'required' : 'optional'}  ${s.name.padEnd(22)} ${s.services.join(', ')}`);
}
